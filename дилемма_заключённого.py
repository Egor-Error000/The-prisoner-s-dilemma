# 5. Система обучения
class PrisonersDilemmaTrainer:
    def __init__(self, bots):
        self.agent = AdaptiveAgent()
        self.metrics = StrategyMetrics(self.agent)
        self.optimizer = torch.optim.Adam(self.agent.parameters(), lr=0.001)
        self.writer = SummaryWriter()
        self.bots = {bot.get_name(): bot for bot in bots}
        self.reward_matrix = {0: {0: 3, 1: 0}, 1: {0: 5, 1: 1}}
        self.analyzer = StrategyAnalyzer(self)
        self.test_interval = 50
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.agent.to(self.device)

    def _get_initial_state(self):
        """Возвращает начальное состояние (нулевой вектор)"""
        return np.zeros(10)

    def _update_state(self, state, my_action, opp_action):
        """Обновляет состояние, добавляя последние действия"""
        new_state = np.roll(state, -2)
        new_state[-2] = my_action
        new_state[-1] = opp_action
        return new_state

    def _compute_episode_loss(self, states, actions, rewards, opp_actions, action_probs_list, opp_probs_list):
        """Вычисляет общий loss для всего эпизода"""
        policy_loss = 0
        prediction_loss = 0
        strategic_loss = 0

        rewards = torch.FloatTensor(rewards).to(self.device)
        actions = torch.LongTensor(actions).to(self.device)
        opp_actions = torch.LongTensor(opp_actions).to(self.device)

        for i in range(len(actions)):
            # Policy loss
            policy_loss += -torch.log(action_probs_list[i][actions[i]]) * rewards[i]

            # Prediction loss
            prediction_loss += nn.CrossEntropyLoss()(
                opp_probs_list[i].unsqueeze(0),
                opp_actions[i].unsqueeze(0)
            )

            # Strategic loss (только после 10 шагов)
            if i > 10 and all(a == actions[i] for a in actions[i-3:i]):
                strategic_loss += -torch.log(action_probs_list[i][actions[i]]) * 2.0

        # Нормализация и регуляризация
        policy_loss /= len(actions)
        prediction_loss /= len(actions)
        strategic_loss = strategic_loss * 0.3 / len(actions) if len(actions) > 0 else 0
        entropy = -torch.mean(torch.sum(torch.stack([p * torch.log(p + 1e-10) for p in action_probs_list], dim=1)))

        return policy_loss + 0.5 * prediction_loss + strategic_loss - 0.01 * entropy

    def _log_metrics(self, metrics, episode, opp_name):
        """Логирует метрики в TensorBoard и консоль"""
        for metric_name, value in metrics.items():
            self.writer.add_scalar(f'{metric_name}/{opp_name}', value, episode)

        if episode % 100 == 0:
            print(f"\nEpisode {episode} vs {opp_name}:")
            print(f"  Reward: {metrics['total_reward']}/500")
            print(f"  Win Rate: {metrics['win_rate']:.1f}%")
            print(f"  Cooperation: {metrics['cooperation_rate']:.1f}%")
            print(f"  Prediction Accuracy: {metrics['prediction_accuracy']:.1f}%")
            print(f"  GPS: {metrics['gps']:.1f}, SIQ: {metrics['siq']:.1f}")

            if episode in self.analyzer.results:
                print("\nCurrent Test Results:")
                for name, res in self.analyzer.results[episode].items():
                    print(f"  {name:<15}: Score={res['score']:5.1f}, Coop={res['cooperation']:5.1f}%, Pred={res['prediction_accuracy']:5.1f}%")

    def _finalize_training(self):
        """Завершающие действия после обучения"""
        self.analyzer.plot_learning_curves()
        self.analyzer.plot_prediction_accuracy()
        self.analyzer.plot_final_comparison()
        torch.save(self.agent.state_dict(), "prisoners_agent.pth")
        self.writer.close()
        print("Training completed and model saved.")

    def train(self, episodes=1000):
        """Основной цикл обучения"""
        epsilon = 0.2
        progress_bar = tqdm(range(episodes), desc="Training")

        for episode in progress_bar:
            opp_name = random.choice(list(self.bots.keys()))
            opponent = self.bots[opp_name]

            self.metrics.reset()
            state = self._get_initial_state()
            history = []

            # Сбор данных эпизода
            states = []
            actions = []
            rewards = []
            opp_actions = []
            action_probs_list = []
            opp_probs_list = []

            for step in range(100):
                state_tensor = torch.FloatTensor(state).to(self.device)

                # Выбор действия
                if random.random() < epsilon:
                    action = random.randint(0, 1)
                    with torch.no_grad():
                        action_probs, opp_probs = self.agent(state_tensor)
                else:
                    action_probs, opp_probs = self.agent(state_tensor)
                    action = torch.multinomial(action_probs, 1).item()

                opp_action = opponent.act(history)
                reward = self.reward_matrix[action][int(opp_action)]

                # Сохранение данных
                states.append(state)
                actions.append(action)
                rewards.append(reward)
                opp_actions.append(opp_action)
                action_probs_list.append(action_probs)
                opp_probs_list.append(opp_probs)

                self.metrics.update(action, opp_action, reward, state)
                history.append(action)
                state = self._update_state(state, action, opp_action)

            # Оптимизация
            loss = self._compute_episode_loss(
                states, actions, rewards,
                opp_actions, action_probs_list, opp_probs_list
            )

            self.optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(self.agent.parameters(), 1.0)
            self.optimizer.step()

            # Уменьшение exploration rate
            epsilon = max(0.01, epsilon * 0.995)

            # Периодическое тестирование
            if episode % self.test_interval == 0:
                self.analyzer.test_strategy(episode)

            # Логирование
            metrics = self.metrics.calculate_all()
            self._log_metrics(metrics, episode, opp_name)

            # Обновление progress bar
            progress_bar.set_postfix({
                'Reward': metrics['total_reward'],
                'Coop%': f"{metrics['cooperation_rate']:.1f}%",
                'GPS': f"{metrics['gps']:.1f}"
            })

        self._finalize_training()
