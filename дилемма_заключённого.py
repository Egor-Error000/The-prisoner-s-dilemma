def train_and_evaluate():
    # Инициализация
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    dataset = PrisonersDilemmaDataset(config)

    # Разделение на train/test
    train_size = int((1 - config.TEST_SIZE) * len(dataset))
    test_size = len(dataset) - train_size
    train_dataset, test_dataset = torch.utils.data.random_split(
        dataset, [train_size, test_size])

    train_loader = DataLoader(
        train_dataset, batch_size=config.BATCH_SIZE, shuffle=True)
    test_loader = DataLoader(
        test_dataset, batch_size=config.BATCH_SIZE)

    # Модель и оптимизация
    model = DNN_LAST(2*config.K + 5, config.HIDDEN_DIM).to(device)
    criterion = nn.BCELoss()
    optimizer = optim.AdamW(model.parameters(), lr=config.LR, weight_decay=1e-4)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, 'min', patience=2, verbose=True)

    # Тренировка
    best_loss = float('inf')
    train_losses, val_losses = [], []

    for epoch in range(config.EPOCHS):
        model.train()
        epoch_loss = 0

        for features, targets in tqdm(train_loader, desc=f"Epoch {epoch+1}"):
            features, targets = features.to(device), targets.to(device)

            optimizer.zero_grad()
            outputs = model(features)
            loss = criterion(outputs, targets)
            loss.backward()

            # Градиентный клиппинг
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()

            epoch_loss += loss.item()

        # Валидация
        val_loss = 0
        model.eval()
        with torch.no_grad():
            for features, targets in test_loader:
                outputs = model(features.to(device))
                val_loss += criterion(outputs, targets.to(device)).item()

        avg_train_loss = epoch_loss / len(train_loader)
        avg_val_loss = val_loss / len(test_loader)

        train_losses.append(avg_train_loss)
        val_losses.append(avg_val_loss)

        scheduler.step(avg_val_loss)

        # Ранняя остановка
        if avg_val_loss < best_loss:
            best_loss = avg_val_loss
            torch.save(model.state_dict(), 'best_model.pth')
            patience = config.EARLY_STOP_PATIENCE
        else:
            patience -= 1
            if patience == 0:
                print("Early stopping triggered!")
                break

        print(f"Train Loss: {avg_train_loss:.4f} | Val Loss: {avg_val_loss:.4f}")

    # Визуализация обучения
    plt.figure(figsize=(12, 5))
    plt.plot(train_losses, label='Train Loss')
    plt.plot(val_losses, label='Validation Loss')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.legend()
    plt.title('Training Progress')
    plt.show()

    # Оценка модели
    evaluate_model(model, test_loader, device)

