class PrisonersDilemmaDataset(Dataset):
    def __init__(self, num_games=1000, K=5, M=5, max_N=20):
        self.num_games = num_games
        self.K = K
        self.M = M
        self.max_N = max_N
        self.strategies = self._init_strategies()
        self.payoff_matrix =  {
            0: {0: (3, 3), 1: (0, 5)},
            1: {0: (5, 0), 1: (1, 1)}
        }
    def __len__(self):
        return self.num_games

    def __getitem__(self, idx):
        while True:
            try:
                features, target = self._generate_sample()
                if not torch.isnan(features).any() and not torch.isinf(features).any():
                    return features, target
            except:
                continue

    def _generate_sample(self):
        strategy1, strategy2 = np.random.choice(self.strategies, 2)
        N = min(np.random.poisson(10), self.max_N)

        # Симуляция игры
        my_moves, opp_moves = [], []
        my_scores, opp_scores = [], []

        for _ in range(N):
            my_move = strategy1(opp_moves)
            opp_move = strategy2(my_moves)
            my_score, opp_score = self.payoff_matrix[my_move][opp_move]

            my_moves.append(my_move)
            opp_moves.append(opp_move)
            my_scores.append(my_score)
            opp_scores.append(opp_score)

        # Извлечение признаков с проверкой
        features = self._extract_features(my_moves, opp_moves, my_scores, opp_scores, N)
        target = torch.FloatTensor([opp_moves[-1] if opp_moves else 0])

        return torch.FloatTensor(features), target

    def _extract_features(self, my_moves, opp_moves, my_scores, opp_scores, N):
        total_rounds = len(opp_moves)

        # История ходов
        recent_me = my_moves[-self.K:] + [0]*(self.K - len(my_moves))
        recent_opp = opp_moves[-self.K:] + [0]*(self.K - len(opp_moves))

        # Основные признаки
        stats = [
            np.clip(sum(opp_moves)/max(total_rounds, 1), 0, 1),
            np.clip(sum(my_scores)/(5*max(total_rounds, 1)), 0, 1),
            0.5,  # mean_N
            0.025, # var_N
            np.clip(total_rounds/self.max_N, 0, 1),
            np.clip((sum(my_scores)+1e-6)/(sum(opp_scores)+1e-6), 0, 10),
            np.clip(sum(opp_moves[-self.M:])/max(min(self.M, total_rounds), 1), 0, 1),
            np.clip(np.var(my_scores[-self.M:])/25 if len(my_scores) > 0 else 0, 0, 1)
        ]

        return recent_me + recent_opp + stats

    def _init_strategies(self):
        return [
            lambda h: h[-1] if h else 0,  # TFT
            lambda h: 1,                  # AlwaysDefect
            lambda h: 0,                  # AlwaysCooperate
            lambda h: np.random.randint(2),# Random
            lambda h: 1 if any(h) else 0, # Grudger
            lambda h: 0 if not h else (1 if h[-1] == 1 else 0)  # SuspiciousTFT
        ]

