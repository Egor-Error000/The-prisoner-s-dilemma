class GRU(nn.Module):
    def __init__(self, input_size=1, hidden_size=5):
        super().__init__()
        self.gru = nn.GRU(input_size, hidden_size, batch_first=True)
        self.fc = nn.Linear(hidden_size, 2)

    def forward(self, x):
        # x: [batch_size, seq_len, input_size]
        out, _ = self.gru(x)
        out = self.fc(out[:, -1, :])
        return torch.softmax(out, dim=-1)

