def enhanced_loss(probs, action, reward, my_history, opp_history,
                 coop_strength=0.5, exploit_penalty=0.4,
                 long_term_penalty=0.2, trend_bonus=0.3):
    """
    Улучшенная функция потерь с:
    - Динамическим бонусом за кооперацию
    - Штрафом за эксплуатацию
    - Учетом долгосрочных последствий
    - Бонусом за следование тренду
    """
    base_loss = -torch.log(probs[0, action]) * reward

    # 1. Адаптивный бонус за кооперацию
    last_opp_move = opp_history[-1] if opp_history else 0
    dynamic_coop_strength = coop_strength * (1 + (1 - last_opp_move))  # Увеличиваем, если оппонент сотрудничал
    coop_bonus = -torch.log(probs[0, 0]) * dynamic_coop_strength

    # 2. Штраф за эксплуатацию с эскалацией
    if action == 1 and reward == 5:
        exploit_count = sum(1 for a, o in zip(my_history[-3:], opp_history[-3:])
                         if a == 1 and o == 0) if len(my_history) >= 3 else 0
        exploit_penalty_scaled = exploit_penalty * (1 + exploit_count)
        exploit_penalty_term = torch.log(probs[0, 1]) * exploit_penalty_scaled
    else:
        exploit_penalty_term = 0

    # 3. Долгосрочный штраф за циклы предательства
    mutual_defections = sum(1 for m, o in zip(my_history[-5:], opp_history[-5:])
                      if m == 1 and o == 1) if len(my_history) >= 5 else 0
    long_term_penalty_term = long_term_penalty * mutual_defections * torch.log(probs[0, action])

    # 4. Бонус за следование тренду
    if len(opp_history) >= 6:
        trend = (sum(1 - x for x in opp_history[-3:]) / 3
               - sum(1 - x for x in opp_history[-6:-3]) / 3)  # Положительный = улучшение
        trend_bonus_term = -trend * torch.log(probs[0, 0]) * trend_bonus
    else:
        trend_bonus_term = 0

    total_loss = (base_loss + coop_bonus + exploit_penalty_term +
                 long_term_penalty_term + trend_bonus_term)

    return total_loss
