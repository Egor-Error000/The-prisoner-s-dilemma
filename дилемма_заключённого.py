class StrategicPlanner:
    def __init__(self, predictor, config):
        self.predictor = predictor
        self.config = config
        self.horizon = 3  # Глубина прогнозирования

    def plan_action(self, history):
        current_state = {
            'my_history': history['my_history'].copy(),
            'opp_history': history['opp_history'].copy()
        }

        best_action = 0
        best_value = -float('inf')

        for candidate_action in [0, 1]:  # Проверяем оба варианта действий
            total_reward = 0
            discount = 1.0
            temp_state = self._simulate_step(current_state, candidate_action)

            for _ in range(self.horizon):
                # Предсказание ответа оппонента
                features = self._extract_features(temp_state)
                with torch.no_grad():
                    opp_prob = self.predictor(torch.FloatTensor([features])).item()
                opp_action = 1 if opp_prob > 0.5 else 0

                # Расчёт награды
                reward = REWARD_MATRIX[candidate_action if _ == 0 else best_action][opp_action]
                total_reward += reward * discount

                # Обновление состояния
                temp_state = self._simulate_step(temp_state, opp_action)
                discount *= 0.9

            if total_reward > best_value:
                best_value = total_reward
                best_action = candidate_action

        return best_action

    def _simulate_step(self, state, action):
        new_state = {
            'my_history': state['my_history'][-(self.config.K-1):] + [action],
            'opp_history': state['opp_history'][-(self.config.K-1):] + [0]  # Заглушка
        }
        return new_state

    def _extract_features(self, state):
        recent_me = state['my_history'][-self.config.K:] + [0]*(self.config.K - len(state['my_history']))
        recent_opp = state['opp_history'][-self.config.K:] + [0]*(self.config.K - len(state['opp_history']))

        total_rounds = len(state['my_history'])
        stats = [
            sum(state['opp_history'])/max(total_rounds, 1),
            sum(state['my_history'])/max(total_rounds, 1),
            total_rounds/self.config.MAX_N,
            sum(state['opp_history'][-self.config.M:])/min(self.config.M, total_rounds),
            np.var(state['opp_history'])/4 if state['opp_history'] else 0
        ]
        return recent_me + recent_opp + stats

