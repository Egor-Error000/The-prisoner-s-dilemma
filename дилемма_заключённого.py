class Detective(Strategy):
    def __init__(self):
        super().__init__("Detective")
        self.sequence = [0, 1, 0, 0]
        self.stage = 0
        self.mode = None

    def act(self):
        if not self.opponent_history:
            return self.sequence[self.stage]

        self.stage += 1

        if self.stage == len(self.sequence) and self.mode is None:
            if sum(self.opponent_history) == 0:
                self.mode = 'always_cooperate'
            elif self.opponent_history == [0, 1, 0, 1]:
                self.mode = 'tit_for_tat'
            else:
                self.mode = 'always_defect'

        if self.mode == 'always_cooperate':
            return 0
        elif self.mode == 'always_defect':
            return 1
        elif self.mode == 'tit_for_tat':
            return self.opponent_history[-1]

        return self.sequence[self.stage] if self.stage < len(self.sequence) else 1

    def reset(self):
        super().reset()
        self.stage = 0
        self.mode = None

