class TitForTat:
    def act(self, history):
        return 0 if not history else history[-1]
    def get_name(self): return "TitForTat"

class TitForTwoTats:
    def __init__(self): self.defect_count = 0
    def act(self, history):
        if not history: return 0
        if history[-1] == 1: self.defect_count += 1
        else: self.defect_count = 0
        return 1 if self.defect_count >= 2 else 0
    def get_name(self): return "TitForTwoTats"

class AlwaysCooperate:
    def act(self, history): return 0
    def get_name(self): return "AlwaysCooperate"

class AlwaysDefect:
    def act(self, history): return 1
    def get_name(self): return "AlwaysDefect"

class RandomBot:
    def act(self, history): return random.randint(0, 1)
    def get_name(self): return "RandomBot"

class Grudger:
    def __init__(self): self.defect_forever = False
    def act(self, history):
        if self.defect_forever: return 1
        if history and 1 in history:
            self.defect_forever = True
            return 1
        return 0
    def get_name(self): return "Grudger"

class SuspiciousTFT:
    def act(self, history): return 1 if not history else history[-1]
    def get_name(self): return "SuspiciousTFT"

class RemorsefulTFT:
    def __init__(self): self.last_action = 0
    def act(self, history):
        if not history: return 0
        if history[-1] == 1 and self.last_action == 1: return 0
        self.last_action = history[-1]
        return self.last_action
    def get_name(self): return "RemorsefulTFT"

class AdaptiveTFT:
    def __init__(self): self.coop_prob = 0.5
    def act(self, history):
        if not history: return 0 if random.random() < self.coop_prob else 1
        if history[-1] == 0: self.coop_prob = min(0.9, self.coop_prob + 0.1)
        else: self.coop_prob = max(0.1, self.coop_prob - 0.1)
        return 0 if random.random() < self.coop_prob else 1
    def get_name(self): return "AdaptiveTFT"

class Detective:
    def __init__(self):
        self.stage = 0
        self.opponent_type = None
        self.sequence = [0, 1, 0, 0]
    def act(self, history):
        if self.stage < len(self.sequence):
            action = self.sequence[self.stage]
            self.stage += 1
            return action
        if self.opponent_type is None:
            if len(history) > 1:
                self.opponent_type = "soft" if history[1] == 0 else "tough"
            else:
                return self.sequence[self.stage % len(self.sequence)]
        return 1 if self.opponent_type == "soft" else (history[-1] if history else 0)
    def get_name(self): return "Detective"

class WinStayLoseShift:
    def __init__(self): self.last_action = 0
    def act(self, history):
        if not history: return 0
        last_reward = 3 if (self.last_action == 0 and history[-1] == 0) else \
                     5 if (self.last_action == 1 and history[-1] == 0) else \
                     1 if (self.last_action == 1 and history[-1] == 1) else 0
        return self.last_action if last_reward >= 3 else 1 - self.last_action
    def get_name(self): return "WinStayLoseShift"

class HardTFT:
    def act(self, history): return 0 if not history else (1 if 1 in history else 0)
    def get_name(self): return "HardTFT"

class AverageCopier:
    def act(self, history): return 0 if not history else (0 if sum(history)/len(history) < 0.5 else 1)
    def get_name(self): return "AverageCopier"

class ReputationBuilder:
    def __init__(self): self.reputation = 0.5
    def act(self, history):
        if not history: return 0
        if history[-1] == 0: self.reputation = min(1.0, self.reputation + 0.1)
        else: self.reputation = max(0.0, self.reputation - 0.2)
        return 0 if random.random() < self.reputation else 1
    def get_name(self): return "ReputationBuilder"

# 2. Модель агента
class AdaptiveAgent(nn.Module):
    def __init__(self, state_size=10):
        super().__init__()
        self.policy_net = nn.Sequential(
            nn.Linear(state_size, 64),
            nn.ReLU(),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 2))

        self.opponent_predictor = nn.Sequential(
            nn.Linear(state_size, 32),
            nn.ReLU(),
            nn.Linear(32, 16),
            nn.ReLU(),
            nn.Linear(16, 2))

    def forward(self, x):
        action_probs = torch.softmax(self.policy_net(x), dim=-1)
        opp_probs = torch.softmax(self.opponent_predictor(x), dim=-1)
        return action_probs, opp_probs

# 3. Система метрик
class StrategyMetrics:
    def __init__(self, agent):
        self.agent = agent
        self.reset()

    def reset(self):
        self.episode_data = {
            'my_actions': [],
            'opp_actions': [],
            'rewards': [],
            'states': []
        }
        self.history = defaultdict(list)

    def update(self, my_action, opp_action, reward, state):
        self.episode_data['my_actions'].append(my_action)
        self.episode_data['opp_actions'].append(opp_action)
        self.episode_data['rewards'].append(reward)
        self.episode_data['states'].append(state)

    def calculate_all(self):
        metrics = {}
        metrics['total_reward'] = sum(self.episode_data['rewards'])
        metrics['win_rate'] = self._calculate_win_rate()
        metrics['cooperation_rate'] = np.mean([1 if a == 0 else 0 for a in self.episode_data['my_actions']])
        metrics['forgiveness_score'] = self._calculate_forgiveness()
        metrics['exploit_efficiency'] = self._calculate_exploit_efficiency()
        metrics['prediction_accuracy'] = self._calculate_prediction_accuracy()
        metrics['gps'] = 0.3*metrics['win_rate'] + 0.2*metrics['cooperation_rate'] + \
                        0.2*metrics['exploit_efficiency'] + 0.3*metrics['prediction_accuracy']
        metrics['siq'] = self._calculate_siq(metrics)

        for k, v in metrics.items():
            self.history[k].append(v)
        return metrics

    def _calculate_win_rate(self):
        rewards = self.episode_data['rewards']
        return (sum(rewards) / (5 * len(rewards))) * 100

    def _calculate_forgiveness(self):
        transitions = sum(1 for i in range(1, len(self.episode_data['my_actions']))
                      if self.episode_data['opp_actions'][i-1] == 1)
        forgiven = sum(1 for i in range(1, len(self.episode_data['my_actions']))
                   if self.episode_data['opp_actions'][i-1] == 1 and self.episode_data['my_actions'][i] == 0)
        return (forgiven / transitions * 100) if transitions > 0 else 50

    def _calculate_exploit_efficiency(self):
        exploit_attempts = sum(1 for a in self.episode_data['my_actions'] if a == 1)
        successful = sum(1 for i, a in enumerate(self.episode_data['my_actions'])
                        if a == 1 and self.episode_data['opp_actions'][i] == 0)
        return (successful / exploit_attempts * 100) if exploit_attempts > 0 else 0

    def _calculate_prediction_accuracy(self):
        correct = 0
        for i in range(1, len(self.episode_data['opp_actions'])):
            state = self.episode_data['states'][i-1]
            with torch.no_grad():
                _, opp_probs = self.agent(torch.FloatTensor(state))
                predicted = torch.argmax(opp_probs).item()
                if predicted == self.episode_data['opp_actions'][i]:
                    correct += 1
        return (correct / (len(self.episode_data['opp_actions']) - 1) * 100) if len(self.episode_data['opp_actions']) > 1 else 50

    def _calculate_siq(self, metrics):
        strategic_decisions = sum(1 for i in range(1, len(self.episode_data['my_actions']))
                           if self.episode_data['opp_actions'][i-1] == 1)
        optimal_decisions = sum(1 for i in range(1, len(self.episode_data['my_actions']))
                          if self.episode_data['opp_actions'][i-1] == 1 and self.episode_data['my_actions'][i] == 1)
        return ((optimal_decisions / strategic_decisions * 100) * 0.6 + metrics['prediction_accuracy'] * 0.4
                if strategic_decisions > 0 else metrics['prediction_accuracy'] * 0.4)

