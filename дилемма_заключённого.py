class StrategyAnalyzer:
    def __init__(self, trainer):
        self.trainer = trainer
        self.results = defaultdict(list)
        self.cooperation_rates = defaultdict(list)
        self.scores = defaultdict(list)
        self.prediction_accuracies = defaultdict(list)
        self.episodes = []

    def test_strategy(self, episode):
        self.trainer.agent.eval()
        test_results = {}

        for opp_name, opponent in self.trainer.bots.items():
            total_reward = 0
            coop_count = 0
            correct_predictions = 0
            total_predictions = 0

            for _ in range(5):
                state = self.trainer._get_initial_state()
                history = []

                for _ in range(100):
                    with torch.no_grad():
                        action_probs, opp_probs = self.trainer.agent(torch.FloatTensor(state))
                    action = torch.argmax(action_probs).item()
                    opp_action = opponent.act(history)

                    predicted = torch.argmax(opp_probs).item()
                    if predicted == opp_action:
                        correct_predictions += 1
                    total_predictions += 1

                    reward = self.trainer.reward_matrix[action][int(opp_action)]
                    total_reward += reward
                    coop_count += 1 if action == 0 else 0

                    history.append(action)
                    state = self.trainer._update_state(state, action, opp_action)

            test_results[opp_name] = {
                'score': total_reward / 5,
                'cooperation': coop_count / 5,
                'prediction_accuracy': correct_predictions / total_predictions * 100
            }

            self.cooperation_rates[opp_name].append(coop_count / 5)
            self.scores[opp_name].append(total_reward / 5)
            self.prediction_accuracies[opp_name].append(correct_predictions / total_predictions * 100)

        self.results[episode] = test_results
        self.episodes.append(episode)
        self.trainer.agent.train()
        return test_results

    def plot_learning_curves(self):
        plt.figure(figsize=(15, 10))

        plt.subplot(2, 1, 1)
        for opp_name, rates in self.cooperation_rates.items():
            plt.plot(self.episodes, rates, label=opp_name)
