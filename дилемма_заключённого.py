class PrisonersDilemmaTrainer:
    def __init__(self):
        self.agent = AdaptiveAgent()
        self.metrics = StrategyMetrics(self.agent)
        self.optimizer = torch.optim.Adam(self.agent.parameters(), lr=0.001)
        self.writer = SummaryWriter()

        # Набор оппонентов для тестирования
        self.opponents = {
            'TitForTat': TitForTat(),
            'AlwaysDefect': AlwaysDefect(),
            'RandomBot': RandomBot(),
            'Grudger': Grudger()
        }

        # Матрица наград
        self.reward_matrix = {
            0: {0: 3, 1: 0},  # Cooperate
            1: {0: 5, 1: 1}   # Defect
        }

    def train(self, episodes=1000):
        for episode in range(episodes):
            # Выбор оппонента (с ротацией)
            opp_name, opponent = random.choice(list(self.opponents.items()))
            self.metrics.reset()

            # Инициализация состояния
            state = self._get_initial_state()
            total_reward = 0

            for step in range(100):  # 100 шагов в игре
                # Выбор действия
                action_probs, opp_probs = self.agent(torch.FloatTensor(state))
                action = torch.multinomial(action_probs, 1).item()

                # Действие оппонента
                opp_action = opponent.act(self.metrics.episode_data['my_actions'])

                # Получение награды
                reward = self.reward_matrix[action][opp_action]
                total_reward += reward

                # Обновление метрик
                self.metrics.update(action, opp_action, reward, state)

                # Расчет лосса
                loss = self._compute_loss(action, reward, action_probs, opp_probs, opp_action)

                # Шаг оптимизации
                self.optimizer.zero_grad()
                loss.backward()
                torch.nn.utils.clip_grad_norm_(self.agent.parameters(), 1.0)
                self.optimizer.step()

                # Обновление состояния
                state = self._update_state(state, action, opp_action)

            # Расчет и логирование метрик
            metrics = self.metrics.calculate_all(episode)
            self._log_metrics(metrics, episode, opp_name)

            # Валидация каждые 100 эпизодов
            if episode % 100 == 0:
                self.validate(episode)

    def _compute_loss(self, action, reward, action_probs, opp_probs, opp_action):
        # Базовый policy loss
        policy_loss = -torch.log(action_probs[action]) * reward

        # Loss предсказания оппонента
        target = torch.LongTensor([opp_action])
        prediction_loss = nn.CrossEntropyLoss()(opp_probs.unsqueeze(0), target)

        # Стратегический компонент
        strategic_loss = self._strategic_component(action, opp_action, action_probs)

        return policy_loss + 0.5 * prediction_loss + 0.3 * strategic_loss

    def _strategic_component(self, action, opp_action, probs):
        # Штраф за повторяющиеся ошибки
        if len(self.metrics.episode_data['my_actions']) > 3:
            last_actions = self.metrics.episode_data['my_actions'][-3:]
            if all(a == action for a in last_actions):
                return -torch.log(probs[action]) * 2.0
        return 0

    def _get_initial_state(self):
        return np.zeros(10)  # 10-мерный вектор состояния

    def _update_state(self, state, my_action, opp_action):
        # Простое обновление - сдвиг истории
        new_state = np.roll(state, -2)
        new_state[-2] = my_action
        new_state[-1] = opp_action
        return new_state

    def _log_metrics(self, metrics, episode, opp_name):
        # Логирование в TensorBoard
        for metric_name, value in metrics.items():
            self.writer.add_scalar(f'{metric_name}/{opp_name}', value, episode)

        # Консольный вывод
        if episode % 50 == 0:
            print(f"\nEpisode {episode} vs {opp_name}:")
            print(f"  Reward: {metrics['total_reward']}/500")
            print(f"  Win Rate: {metrics['win_rate']:.1f}%")
            print(f"  Cooperation: {metrics['cooperation_rate']:.1f}%")
            print(f"  Forgiveness: {metrics['forgiveness_score']:.1f}%")
            print(f"  GPS: {metrics['gps']:.1f}, SIQ: {metrics['siq']:.1f}")

    def validate(self, episode):
        results = {}
        for opp_name, opponent in self.opponents.items():
            total_reward = 0
            for _ in range(10):  # 10 валидационных игр
                state = self._get_initial_state()
                episode_reward = 0

                for _ in range(100):
                    with torch.no_grad():
                        action_probs, _ = self.agent(torch.FloatTensor(state))
                    action = torch.argmax(action_probs).item()
                    opp_action = opponent.act([])  # Empty history for validation
                    reward = self.reward_matrix[action][opp_action]
                    episode_reward += reward
                    state = self._update_state(state, action, opp_action)

                total_reward += episode_reward

            avg_reward = total_reward / 10
            results[opp_name] = avg_reward
            self.writer.add_scalar(f'validation/{opp_name}', avg_reward, episode)

        # Визуализация
        plt.figure(figsize=(10, 5))
        plt.bar(results.keys(), results.values())
        plt.title(f'Validation Results (Episode {episode})')
        plt.ylabel('Average Reward')
        plt.ylim(0, 500)
        plt.show()

    def final_evaluation(self):
        # Подробный финальный отчет
        print("\nFinal Evaluation:")
        results = []

        for opp_name, opponent in self.opponents.items():
            metrics = defaultdict(list)

