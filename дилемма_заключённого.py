class TitForTwoTats:
    def __init__(self):
        self.defect_count = 0

    def act(self, history):
        if not history:
            return 0
        if history[-1] == 1:
            self.defect_count += 1
        else:
            self.defect_count = 0
        return 1 if self.defect_count >= 2 else 0

    def get_name(self):
        return "TitForTwoTats"

