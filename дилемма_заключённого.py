    def _generate_all_pairings(self):
        data = []
        total_combinations = len(self.strategies) * len(self.strategies)

        with tqdm(total=total_combinations, desc="Generating all strategy pairs") as pbar:
            for i, s1 in enumerate(self.strategies):
                for j, s2 in enumerate(self.strategies):
                    # Генерируем несколько игр для каждой пары стратегий
                    for _ in range(self.config.GAMES_PER_PAIR):
                        game_data = self._generate_game(s1, s2)
                        data.extend(game_data)
                    pbar.update(1)

        return data

    def _generate_game(self, s1, s2):
        s1.reset()
        s2.reset()

        N = min(np.random.poisson(10), self.config.MAX_N)
        samples = []

        for _ in range(N):
            # Получаем ходы от стратегий (без передачи истории)
            my_move = s1.act()
            opp_move = s2.act()

            # Обновляем истории внутри стратегий
            s1.update(my_move, opp_move)
            s2.update(opp_move, my_move)

            # Генерируем примеры после 2+ раундов
            if len(s1.opponent_history) >= 2:
                features = self._extract_features(s1)
                target = opp_move
                samples.append((torch.FloatTensor(features),
                              torch.FloatTensor([target])))

        return samples

    def _extract_features(self, strategy):
        """Извлекает признаки на основе истории стратегии"""
        history = strategy.opponent_history
        my_history = strategy.history
        total_rounds = len(history)

        # История последних K ходов
        recent_opp = history[-self.config.K:] + [0]*(self.config.K - len(history))
        recent_me = my_history[-self.config.K:] + [0]*(self.config.K - len(my_history))

        # Статистики
        stats = [
            sum(history)/max(total_rounds, 1),  # % предательств оппонента
            sum(my_history)/max(total_rounds, 1),  # % моих предательств
            total_rounds/self.config.MAX_N,  # Прогресс игры
            sum(history[-self.config.M:])/min(self.config.M, total_rounds),  # Тренд
            np.var(history)/4 if len(history) > 0 else 0  # Нормализованная дисперсия
        ]

        return recent_me + recent_opp + stats

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        return self.data[idx]

