import torch
import torch.nn as nn
import torch.optim as optim
import numpy as np
import random
from collections import deque
import matplotlib.pyplot as plt

# Конфигурация
class Config:
    seq_length = 10  # Длина последовательности для LSTM
    lstm_input_size = 4  # [my_action, opp_action, my_avg, opp_avg]
    lstm_hidden_size = 64
    strategy_input_size = lstm_hidden_size + 4  # + контекстные признаки
    strategy_hidden_size = 32
    batch_size = 32
    lr = 0.001
    gamma = 0.95
    epsilon_start = 1.0
    epsilon_min = 0.01
    epsilon_decay = 0.995
    memory_capacity = 10000
    max_rounds = 100

# LSTM для предсказания оппонента
class OpponentLSTM(nn.Module):
    def __init__(self, input_size, hidden_size):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, batch_first=True)
        self.fc = nn.Linear(hidden_size, 1)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        lstm_out, _ = self.lstm(x)
        last_out = lstm_out[:, -1, :]  # Берем последний выход последовательности
        return self.sigmoid(self.fc(last_out))

# Стратегическая сеть
class StrategyNet(nn.Module):
    def __init__(self, input_size, hidden_size):
        super().__init__()
        self.fc1 = nn.Linear(input_size, hidden_size)
        self.fc2 = nn.Linear(hidden_size, 2)  # 2 действия

    def forward(self, x):
        x = torch.relu(self.fc1(x))
        return self.fc2(x)

# Агент
class DualNetworkAgent:
    def __init__(self, config):
        self.config = config
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # Инициализация моделей
        self.predictor = OpponentLSTM(config.lstm_input_size, config.lstm_hidden_size).to(self.device)
        self.strategy = StrategyNet(config.strategy_input_size, config.strategy_hidden_size).to(self.device)

        # Оптимизаторы
        self.optimizer_p = optim.Adam(self.predictor.parameters(), lr=config.lr)
        self.optimizer_s = optim.Adam(self.strategy.parameters(), lr=config.lr)

        # Память для обучения
        self.memory = deque(maxlen=config.memory_capacity)
        self.epsilon = config.epsilon_start
        self.reset()

    def reset(self):
        self.history = {'my_actions': [], 'opp_actions': []}

    def _get_features(self, idx):
        """Извлекает признаки для одного временного шага"""
        if idx >= len(self.history['my_actions']) or idx < 0:
            return [0, 0, 0.0, 0.0]  # Заполнитель

        # Вычисляем скользящие средние
        my_window = self.history['my_actions'][max(0, idx-4):idx+1]  # Последние 5 действий
        opp_window = self.history['opp_actions'][max(0, idx-4):idx+1]

        return [
            self.history['my_actions'][idx],
            self.history['opp_actions'][idx],
            np.mean(my_window) if my_window else 0.0,
            np.mean(opp_window) if opp_window else 0.0
        ]

    def _create_sequence(self):
        """Создает последовательность для LSTM"""
        seq = []
        start_idx = max(0, len(self.history['my_actions']) - self.config.seq_length)

        for i in range(start_idx, len(self.history['my_actions'])):
            seq.append(self._get_features(i))

        # Дополняем нулями если нужно
        while len(seq) < self.config.seq_length:
            seq.insert(0, [0, 0, 0.0, 0.0])

        return torch.FloatTensor(seq).to(self.device)  # [seq_len, features]

    def act(self, training=True):
        if len(self.history['my_actions']) < self.config.seq_length or random.random() < self.epsilon:
            return random.choice([0, 1])

        # Получаем последовательность и добавляем размерность батча
        seq = self._create_sequence().unsqueeze(0)  # [1, seq_len, features]

        # Предсказание оппонента
        with torch.no_grad():
            opp_pred = self.predictor(seq)

        # Контекстные признаки
        context = torch.FloatTensor([
            np.mean(self.history['my_actions'][-5:] or [0]),
            np.mean(self.history['opp_actions'][-5:] or [0]),
            len(self.history['my_actions']) / self.config.max_rounds,
            self.epsilon
        ]).to(self.device)

        # Принимаем решение
        strategy_input = torch.cat([opp_pred.squeeze(0), context], dim=0).unsqueeze(0)
        q_values = self.strategy(strategy_input)
        return torch.argmax(q_values).item()

    def store_experience(self, state, action, reward, next_state, done):
        self.memory.append((
            state.cpu().numpy(),
            action,
            reward,
            next_state.cpu().numpy(),
            done
        ))

    def train(self):
        if len(self.memory) < self.config.batch_size:
            return

        batch = random.sample(self.memory, self.config.batch_size)
        states, actions, rewards, next_states, dones = zip(*batch)

        # Подготовка данных для LSTM
        state_tensor = torch.FloatTensor(np.array(states)).to(self.device)  # [batch, seq_len, features]
        next_state_tensor = torch.FloatTensor(np.array(next_states)).to(self.device)

        # 1. Обучение предсказателя
        self.optimizer_p.zero_grad()
        preds = self.predictor(state_tensor).squeeze()  # [batch]

        # Целевые значения - последние действия оппонента
        targets = torch.FloatTensor([s[-1, 1] for s in states]).to(self.device)
        loss_p = nn.BCELoss()(preds, targets)
        loss_p.backward()
        self.optimizer_p.step()

        # 2. Обучение стратегии
        self.optimizer_s.zero_grad()

        # Контекстные признаки
        contexts = torch.FloatTensor([
            [
                np.mean(s[-5:, 0]),  # Среднее наших последних 5 действий
                np.mean(s[-5:, 1]),  # Среднее действий оппонента
                len(s) / self.config.max_rounds,  # Прогресс игры
                self.epsilon  # Текущий уровень исследования
            ]
            for s in states
        ]).to(self.device)

        # Предсказания оппонента (без вычисления градиентов)
        with torch.no_grad():
            opp_preds = self.predictor(state_tensor)

        # Вход стратегической сети
        strategy_input = torch.cat([opp_preds, contexts], dim=1)

        # Q-значения для текущих состояний
        current_q = self.strategy(strategy_input)
        gathered_q = current_q.gather(1, torch.LongTensor(actions).unsqueeze(1).to(self.device))

        # Q-значения для следующих состояний (без градиентов)
        with torch.no_grad():
            next_opp_preds = self.predictor(next_state_tensor)
            next_contexts = torch.FloatTensor([
                [
                    np.mean(s[-5:, 0]),
                    np.mean(s[-5:, 1]),
                    len(s) / self.config.max_rounds,
                    self.epsilon
                ]
                for s in next_states
            ]).to(self.device)
            next_q = self.strategy(torch.cat([next_opp_preds, next_contexts], dim=1)).max(1)[0]

        # Целевые Q-значения
        targets = torch.FloatTensor(rewards).to(self.device) + \
                 self.config.gamma * next_q * (1 - torch.FloatTensor(dones).to(self.device))

        # Потери
        loss_s = nn.MSELoss()(gathered_q.squeeze(), targets)
        loss_s.backward()
        self.optimizer_s.step()

        # Уменьшаем epsilon
        self.epsilon = max(self.config.epsilon_min, self.epsilon * self.config.epsilon_decay)

# Функция обучения
def train_agent(agent, strategies, num_episodes=200):
    rewards = []

    for episode in range(num_episodes):
        opponent = random.choice(strategies)
        agent.reset()
        opponent.reset()

        # Инициализация истории
        for _ in range(agent.config.seq_length):
            action = random.choice([0, 1])
            opp_action = opponent.act()
            agent.history['my_actions'].append(action)
            agent.history['opp_actions'].append(opp_action)
            opponent.update(action, opp_action)

        total_reward = 0
        state = agent._create_sequence()

        for _ in range(agent.config.seq_length, agent.config.max_rounds):
            action = agent.act(training=True)
            opp_action = opponent.act()

            reward = REWARD_MATRIX[action][opp_action]
            total_reward += reward

            # Обновляем историю
            agent.history['my_actions'].append(action)
            agent.history['opp_actions'].append(opp_action)
            next_state = agent._create_sequence()

            # Сохраняем опыт
            agent.store_experience(state, action, reward, next_state, False)
            agent.train()

            state = next_state
            opponent.update(action, opp_action)

        rewards.append(total_reward)
        print(f"Episode {episode+1}/{num_episodes}, Reward: {total_reward}, Epsilon: {agent.epsilon:.3f}")

    # Визуализация
    plt.figure(figsize=(12, 6))
    plt.plot(rewards, label='Награда за эпизод')

    # Скользящее среднее для наглядности
    window_size = max(10, num_episodes // 20)
    moving_avg = np.convolve(rewards, np.ones(window_size)/window_size, mode='valid')
    plt.plot(range(window_size-1, len(rewards)), moving_avg, label=f'Скользящее среднее ({window_size})', color='red')

    plt.title("Динамика обучения агента")
    plt.xlabel("Эпизод")
    plt.ylabel("Награда")
    plt.legend()
    plt.grid(True)
    plt.show()

